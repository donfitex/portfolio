from django.contrib import admin

from .models import Experience, Project, ProjectEmbedding, SiteSettings


@admin.register(Project)
class ProjectAdmin(admin.ModelAdmin):
    list_display = ("title", "category", "featured", "is_published", "order", "updated_at")
    list_filter = ("category", "featured", "is_published")
    list_editable = ("featured", "is_published", "order")
    search_fields = ("title", "description")
    prepopulated_fields = {"slug": ("title",)}


@admin.register(ProjectEmbedding)
class ProjectEmbeddingAdmin(admin.ModelAdmin):
    list_display = ("project", "created_at")
    exclude = ("embedding",)  # 1536 numbers aren't editable by hand; generated by code in Section 2


@admin.register(Experience)
class ExperienceAdmin(admin.ModelAdmin):
    list_display = ("role", "company", "start_date", "end_date", "current")
    list_filter = ("current",)


@admin.register(SiteSettings)
class SiteSettingsAdmin(admin.ModelAdmin):
    def has_add_permission(self, request):
        return not SiteSettings.objects.exists()

    def has_delete_permission(self, request, obj=None):
        return False